// Aula 4 - Exercício 1
// Solicita dia, mês e ano e exibe a data informada.
#include <iostream>
using namespace std;

int main() {
    int dia, mes, ano;

    cout << "Digite o dia: ";
    cin >> dia;
    cout << "Digite o mes: ";
    cin >> mes;
    cout << "Digite o ano: ";
    cin >> ano;

    cout << "\nData informada: " << dia << "/" << mes << "/" << ano << endl;

    return 0;
}
